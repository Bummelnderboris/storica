INVENTION_POLICY = """# What prose may invent, and what it may not

Canon records what the story has decided. Everything it has not decided is the writer's to
imagine, and imagining it is the job: a scene is made of specifics nobody planned.

MAY be invented freely — once the chapter passes, it is recorded into canon and later chapters are
held to it:
- the texture of the world: objects, rooms, weather, light, sound, smell, food, clothing;
- minor specifics: a date, an hour, a distance, a street, a file number, a brand of cigarettes;
- procedure: how a form is filled in, how a body is moved, how an office does its business;
- unnamed walk-ons the scene needs (a driver, a clerk, a waitress), as long as they stay unnamed
  and change nothing the plot depends on.

MAY NOT be invented:
- anything that contradicts a line of canon;
- a NAMED person canon does not have, or a relationship between people canon does not record;
- a change to who knows what — the knowledge table is binding, and a character may not learn,
  suspect or reveal anything it does not grant them;
- the answer to a question the story is built around. What the premise, a character's secret, a
  knowledge item or an open promise leaves undecided is undecided on purpose; settling it in a
  subordinate clause takes it away from the chapter that is meant to settle it."""
